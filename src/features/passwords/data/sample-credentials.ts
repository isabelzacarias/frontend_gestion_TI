const serviceOccurrences = new Map<string, number>()

export const sampleCredentials = credentialSamples.map((credential) => {
  const occurrence = (serviceOccurrences.get(credential.id) ?? 0) + 1
  serviceOccurrences.set(credential.id, occurrence)

  return {
    ...credential,
    id: `${credential.id}-${occurrence}`,
    account:
      occurrence === 1
        ? credential.account
        : credential.account.replace("@", `+${occurrence}@`),
    username:
      occurrence === 1
        ? credential.username
        : `${credential.username}-${occurrence}`,
    service:
      occurrence === 1
        ? credential.service
        : `${credential.service} (${occurrence})`,
  }
})
